'use strict';
const assert=require('node:assert/strict');
const {compile}=require('../../scripts/operations/compile_lead_outcomes');
const mk=(stage,extra={})=>({lead_id:'lead_test_001',vertical:'uscis_medical',stage,evidence_ref:'https://example.test/evidence/'+stage,observed_at:'2026-10-30T09:00:00Z',...extra});
const empty=compile({events:[]});
assert.equal(empty.lead_count,0);
assert.equal(empty.revenue_evidence_present,false);
assert.equal(empty.verified_revenue_cents,0);
const one=compile({events:[mk('submitted'),mk('stored'),mk('provider_delivered')]});
assert.equal(one.stage_counts.submitted,1);
assert.equal(one.stage_counts.provider_accepted,0);
assert.equal(one.rows[0].revenue_cents,null);
const complete=compile({events:['submitted','stored','provider_delivered','provider_accepted','converted'].map(x=>mk(x)).concat(mk('revenue_received',{amount_cents:15000,currency:'USD'}))});
assert.equal(complete.errors.length,0);
assert.equal(complete.verified_revenue_cents,15000);
assert.equal(complete.stage_counts.revenue_received,1);
const skipped=compile({events:[mk('submitted'),mk('provider_accepted')]});
assert.equal(skipped.lead_count,0);
assert.ok(skipped.errors.some(x=>x.reason==='missing_predecessor'));
const bad=compile({events:[mk('submitted'),mk('stored'),mk('provider_delivered'),mk('provider_accepted'),mk('converted'),mk('revenue_received',{amount_cents:'15000',currency:'USD'})]});
assert.equal(bad.lead_count,0);
assert.ok(bad.errors.some(x=>x.reason==='invalid_revenue'));
const junk=compile({events:[{...mk('submitted'),lead_id:'contact@example.com'}]});
assert.equal(junk.lead_count,0);
assert.ok(junk.errors.some(x=>x.reason==='invalid_evidence_event'));
console.log('lead outcome evidence compiler PASS');
